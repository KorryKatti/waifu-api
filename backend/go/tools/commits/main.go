// Command commits regenerates the bundle of reachable commits that the instance
// index resolves against.
//
// # Why this exists
//
// GET /version lets an instance report the commit it was built from, and the
// index uses that to say whether the instance is running code from this
// repository. Answering it needs this repository's history, and the running
// service cannot read it: the build context is backend/go and .git is at the
// repository root, so no VCS metadata is in the image.
//
// The history is therefore bundled into the binary at build time from a
// committed file.
//
// # Running it
//
// From backend/go, which is anywhere inside the repository — git finds .git from
// any subdirectory, and this module's root is not the repository root:
//
//	go run ./tools/commits
//
// Run it after merging. The bundle is a snapshot, so a commit made after the last
// regeneration does not resolve, and an instance running this repository's own
// newest code is reported as "could not tell" rather than as upstream. That is
// the safe direction of the two, but it is a direction, and the fix is one
// command.
//
// CI runs tools/checkcommits, which fails when the bundle is stale, so an
// un-regenerated bundle is caught rather than discovered by a reader wondering
// why the canonical instance is not recognised.
package main

import (
	"bufio"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// bundlePath is where the generated file goes.
//
// It is relative to the working directory, not to this package, matching
// tools/routecheck: both are run from backend/go with `go run ./tools/...`, and
// a path anchored to the source file would be wrong for anyone who ran the
// command from elsewhere.
const bundlePath = "internal/instances/upstream_commits.txt"

// keyLength is the number of hex characters stored per commit.
//
// Twelve is 48 bits. The birthday bound puts the odds of a collision inside a
// few thousand commits at around one in a hundred million, which is low enough
// that a collision would show up as a wrong commit age for one instance rather
// than as a security problem.
const keyLength = 12

func main() {
	lines, err := reachableCommits()
	if err != nil {
		fail(err)
	}

	path, err := filepath.Abs(bundlePath)
	if err != nil {
		fail(err)
	}

	var out strings.Builder
	out.WriteString("# Generated by tools/commits. Do not edit.\n")
	out.WriteString("#\n")
	out.WriteString("# One reachable commit per line: the first 12 hex characters of the\n")
	out.WriteString("# hash, a tab, and the commit date as Unix seconds. The index resolves\n")
	out.WriteString("# an instance's reported commit against this file to decide whether it\n")
	out.WriteString("# is running code from this repository.\n")
	out.WriteString("#\n")
	out.WriteString("# Regenerate from the repository root with: go run ./tools/commits\n")

	for _, line := range lines {
		out.WriteString("\n")
		out.WriteString(line)
	}

	if err := os.WriteFile(path, []byte(out.String()), 0o644); err != nil {
		fail(fmt.Errorf("write %s: %w", path, err))
	}

	fmt.Printf("wrote %d commits to %s\n", len(lines), path)
}

// commit is one line of the bundle.
type commit struct {
	hash   string
	unix   int64
	pretty string
}

// reachableCommits reads the history with git and reduces it to the bundle's
// lines.
//
// The ordering is chronological rather than topological so the diff between two
// generated bundles is small and readable when history is rebased: a rebase
// rewrites hashes and moves entries, and sorting by date keeps unrelated lines
// from shifting.
func reachableCommits() ([]string, error) {
	format := "%H%x09%ct"
	raw, err := exec.Command("git", "log", "--all", "--format="+format).Output()
	if err != nil {
		return nil, fmt.Errorf("read git history (run this from inside the repository): %w", err)
	}

	var commits []commit
	scanner := bufio.NewScanner(strings.NewReader(string(raw)))
	for scanner.Scan() {
		fields := strings.Split(scanner.Text(), "\t")
		if len(fields) != 2 {
			continue
		}

		hash := strings.ToLower(fields[0])
		if len(hash) < keyLength {
			continue
		}

		unix, err := strconv.ParseInt(fields[1], 10, 64)
		if err != nil {
			continue
		}

		commits = append(commits, commit{hash: hash[:keyLength], unix: unix})
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("read git output: %w", err)
	}

	sort.Slice(commits, func(i, j int) bool {
		if commits[i].unix != commits[j].unix {
			return commits[i].unix < commits[j].unix
		}
		return commits[i].hash < commits[j].hash
	})

	lines := make([]string, 0, len(commits))
	seen := make(map[string]bool, len(commits))
	for _, entry := range commits {
		// A prefix collision would make one entry silently shadow another.
		if seen[entry.hash] {
			continue
		}
		seen[entry.hash] = true
		lines = append(lines, entry.hash+"\t"+strconv.FormatInt(entry.unix, 10))
	}
	return lines, nil
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "commits: %v\n", err)
	os.Exit(1)
}
